function rep(file, s, tag, find, to) {
  const n = s.split(find).length - 1;
  if (n !== 1) { log.push('  [FAIL ' + n + '] ' + file + ' :: ' + tag); fail++; return s; }
  log.push('  [ok] ' + file + ' :: ' + tag);
  return s.replace(find, to);
}

