package com.ruoyi.system.domain;

import com.baomidou.mybatisplus.annotation.IdType;
import com.baomidou.mybatisplus.annotation.TableId;
import com.baomidou.mybatisplus.annotation.TableLogic;
import com.baomidou.mybatisplus.annotation.TableName;
import com.ruoyi.common.core.domain.BaseEntity;
import lombok.Data;
import lombok.EqualsAndHashCode;

import java.math.BigDecimal;

/**
 * 结算成本项明细 settlement_cost_item（M36 T36.1）
 * <p>两类：EMPLOYEE=员工成本（由 activity_staff_snapshot 快照自动生成，不可手填）
 *         OTHER=其他成本（场地/物料/代付等，可手填）。
 * <p>代收代付配对：存在代收收入（COLLECTED）时应有对应代付成本（OTHER 类型，remark 标注）。
 *
 * @author ruoyi
 * @date 2026-10-19
 */
@Data
@EqualsAndHashCode(callSuper = true)
@TableName("settlement_cost_item")
public class SettlementCostItem extends BaseEntity {

    private static final long serialVersionUID = 1L;

    /** 主键ID */
    @TableId(value = "id", type = IdType.AUTO)
    private Long id;

    /** 租户ID */
    private Long tenantId;

    /** FK→activity_settlement.id */
    private Long settlementId;

    /** 成本项名称 */
    private String itemName;

    /** 类型：EMPLOYEE=员工成本（快照自动生成）/ OTHER=其他成本（可手填） */
    private String costType;

    /** 金额（代付成本为正值，与代收配对） */
    private BigDecimal amount;

    /** EMPLOYEE 类型时关联员工（sys_user.user_id） */
    private Long staffId;

    /** EMPLOYEE 类型时关联 activity_staff_snapshot.id */
    private Long snapshotId;

    /** 是否自动生成（员工成本=1，其他成本=0） */
    private Integer isAutoGenerated;

    /** 排序 */
    private Integer sortOrder;

    /** 备注（代付说明等） */
    private String remark;

    /** 删除标志（0存在 2删除） */
    @TableLogic
    private String delFlag;
}
